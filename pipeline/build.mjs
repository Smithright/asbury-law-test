// Compiles pipeline/src + pipeline/env/<slot>.json into pipeline/dist/<slot>/ (what clasp pushes).
// Usage: node pipeline/build.mjs [slot ...]   (no args = every slot). Fails on any invalid env file.
import { readFileSync, writeFileSync, mkdirSync, readdirSync, copyFileSync, rmSync } from "node:fs";
import { execSync } from "node:child_process";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const root = dirname(fileURLToPath(import.meta.url));
const SLOTS = { testing: "testing", "prod-blue": "production", "prod-green": "production" };
const sha = process.env.GITHUB_SHA || execSync("git rev-parse HEAD", { cwd: root }).toString().trim();
const wanted = process.argv.slice(2).length ? process.argv.slice(2) : readdirSync(join(root, "env")).map((f) => f.replace(/\.json$/, ""));

for (const slot of wanted) {
  const env = JSON.parse(readFileSync(join(root, "env", slot + ".json"), "utf8"));
  if (env.slot !== slot) throw new Error(`${slot}: env.slot is ${env.slot}`);
  if (SLOTS[slot] !== env.env) throw new Error(`${slot}: env must be ${SLOTS[slot]}, got ${env.env}`);
  // Every slot is symmetric: the script runs as the booking page's owner, on that owner's primary calendar.
  if (env.calendarId !== null) throw new Error(`${slot}: calendarId must be null (owner's primary calendar)`);
  if (env.env === "production" && /testing|staging/.test(env.secret)) throw new Error(`${slot}: production cannot use a testing secret`);
  const out = join(root, "dist", slot);
  rmSync(out, { recursive: true, force: true });
  mkdirSync(out, { recursive: true });
  copyFileSync(join(root, "src", "Code.gs"), join(out, "Code.gs"));
  copyFileSync(join(root, "src", "appsscript.json"), join(out, "appsscript.json"));
  const ENV = { slot: env.slot, env: env.env, calendarId: env.calendarId, secret: env.secret, build: sha };
  writeFileSync(join(out, "Config.gs"), `// GENERATED by pipeline/build.mjs from env/${slot}.json at ${sha}. Do not edit.\nconst ENV = Object.freeze(${JSON.stringify(ENV, null, 2)});\n`);
  writeFileSync(join(out, ".clasp.json"), JSON.stringify({ scriptId: env.scriptId, rootDir: "." }, null, 2) + "\n");
  console.log(`built ${slot} -> ${out} (${env.scriptId})`);
}
